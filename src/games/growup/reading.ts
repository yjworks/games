const trackPool = (t: Track) => READINGS.filter((r) => t.topics.includes(r.topic) && questionsOf(r).length);

/** 이 인증에서 지금까지 배운 것 / 전체 */
export function trackProgress(read: readonly string[], t: Track): { done: number; total: number } {
  const pool = trackPool(t);
  return { done: pool.filter((r) => read.includes(r.id)).length, total: pool.length };
}

/** 단계 시험을 보려면 배워야 하는 개수 — 전체의 30% · 60% · 90% */
export function levelNeed(t: Track, level: number): number {
  const total = trackPool(t).length;
  return Math.max(EXAM_SIZE, Math.ceil(total * [0, 0.3, 0.6, 0.9][level]));
}

/** 시험 — 배운 것에서 5문제 */
export function makeExam(read: readonly string[], t: Track, rand: () => number): Quiz[] {
  const learned = trackPool(t).filter((r) => read.includes(r.id));
  const out: Quiz[] = [];
  for (const r of pick(rand, learned, learned.length)) {
    const q = quizFrom(r, rand);
    if (q) out.push(q);
    if (out.length >= EXAM_SIZE) break;
  }
  return out;
}

/** 진로에 더해 줄 인증 점수 — 그 분야에 이어진 인증의 단계 합 × 2, 많아야 6 */
export function certBonus(certs: Record<string, number> | undefined, field: FieldKey | null | undefined, field2?: FieldKey | null): number {
  if (!certs || !field) return 0;
  let sum = 0;
  for (const t of TRACKS) {
    const lv = certs[t.id] ?? 0;
    if (lv && (t.fields.includes(field) || (field2 && t.fields.includes(field2)))) sum += lv;
  }
  return Math.min(6, sum * 2);
}

