const BY_ID = new Map(READINGS.map((r) => [r.id, r]));
export const readingById = (id: string) => BY_ID.get(id);

/**
 * 이번 달 읽을거리 — 낱말은 아직 안 읽은 것을 순서대로(쉬운 것부터),
 * 상식은 안 읽은 것 가운데 아무거나. 다 읽었으면 복습으로 아무거나.
 */
export function pickReading(read: readonly string[], place: PlaceId, act: string, rand: () => number): Reading | null {
  const words = BY_ACT[act];
  if (words) return words.find((r) => !read.includes(r.id)) ?? words[Math.floor(rand() * words.length)];
  const pool = (FACTS[place] ?? []).filter((r) => !r.acts || r.acts.includes(act));
  if (!pool.length) return null;
  const fresh = pool.filter((r) => !read.includes(r.id));
  const from = fresh.length ? fresh : pool;
  return from[Math.floor(rand() * from.length)];
}

/** 퀴즈로 낼 수 있는 [낱말, 뜻]들 */
export function quizTerms(r: Reading): [string, string][] {
  if (r.rows) return r.rows;
  return r.term ? [r.term] : [];
}

/** 같은 종류의 다른 뜻들(오답 후보) */
export function meaningsOf(kind: ReadKind): string[] {
  return [...new Set(READINGS.filter((r) => r.kind === kind).flatMap((r) => quizTerms(r).map((t) => t[1])))];
}

export const QUIZ_KINDS: ReadKind[] = ['english', 'hanja', 'idiom', 'proverb'];

/** 낱말 퀴즈 물음 */
export function wordQuestion(kind: ReadKind, word: string): string {
  switch (kind) {
    case 'english': return `영어 “${word}”의 뜻은?`;
    case 'hanja': return `한자 ‘${word}’의 뜻과 소리는?`;
    case 'idiom': return `고사성어 ‘${word}’의 뜻은?`;
    default: return `속담 “${word}”의 뜻은?`;
  }
}
