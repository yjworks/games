/** 퀴즈로 낼 수 있는 [낱말, 뜻]들 — 영어·한자·속담·고사성어 */
export function quizTerms(r: Reading): [string, string][] {
  if (r.rows) return r.rows;
  return r.term ? [r.term] : [];
}

/** 같은 종류의 다른 뜻들(오답 후보) */
export function meaningsOf(kind: ReadKind): string[] {
  return [...new Set(READINGS.filter((x) => x.kind === kind).flatMap((x) => quizTerms(x).map((t) => t[1])))];
}

export const QUIZ_KINDS: ReadKind[] = ['english', 'hanja', 'idiom', 'proverb'];

/** 낱말 퀴즈 물음 */
export function wordQuestion(kind: ReadKind, word: string): string {
  switch (kind) {
    case 'english': return `영어 “${word}”의 뜻은?`;
    case 'hanja': return `한자 ‘${word}’의 뜻과 소리는?`;
    case 'idiom': return `고사성어 ‘${word}’의 뜻은?`;
    default: return `속담 “${word}”의 뜻은?`;
  }
}

/** 읽을거리 하나로 낼 수 있는 문제들 [물음, 정답, 오답 후보들] */
export function questionsOf(r: Reading): { question: string; answer: string; wrong: string[] }[] {
  if (r.q) return [{ question: r.q[0], answer: r.q[1], wrong: r.q.slice(2) }];
  return quizTerms(r).map(([w, m]) => ({ question: wordQuestion(r.kind, w), answer: m, wrong: meaningsOf(r.kind).filter((x) => x !== m) }));
}

function pick<T>(rand: () => number, list: T[], n: number): T[] {
  const left = [...list];
  const out: T[] = [];
  while (out.length < n && left.length) out.push(left.splice(Math.floor(rand() * left.length), 1)[0]);
  return out;
}

/** 읽을거리 하나로 4지선다 문제를 만든다 */
export function quizFrom(r: Reading, rand: () => number): Quiz | null {
  const qs = questionsOf(r);
  if (!qs.length) return null;
  const q = qs[Math.floor(rand() * qs.length)];
  const wrong = pick(rand, q.wrong.filter((x) => x !== q.answer), 3);
  if (wrong.length < 3) return null;
  const at = Math.floor(rand() * 4);
  const options = [...wrong];
  options.splice(at, 0, q.answer);
  return { kind: 'word', readingId: r.id, question: q.question, options: options as Quiz['options'], answer: at };
}

